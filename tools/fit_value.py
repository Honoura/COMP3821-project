#!/usr/bin/env python3
"""Fit the online value table to offline DP results and write
simulator/include/value_table.h.

Input: files written by dp.cpp when DP_DUMP is set, one per sequence:

    cd simulator
    c++ -std=c++17 -O2 -pthread -Iinclude runner/runner.cpp strategies/dp.cpp -o run_dp
    for s in $(seq 1001 1040); do DP_DUMP=../output/values/seed$s.json ./run_dp --seed $s --out /dev/null; done
    python3 ../tools/fit_value.py ../output/values/*.json

Use different seeds from the ones you evaluate on.

The model is  V(i, h) = alpha * (pieces left) + theta(h, b),  b = (i - 1) mod 7,
where (i, h) is a boundary state: i pieces drawn, h in hold. The DP gives the
value for several held pieces at the same position of the same sequence, and
those share the same future. So the fit has a separate level for every
(sequence, position), which compares held pieces on the same future, and then
explains the levels by alpha * (pieces left) and the bag offset. States with
fewer than 30 pieces left are left out, because the value flattens to 0 near
the end of a sequence.
"""

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

PIECES = "IOTLJSZ"          # the order of tetris.h
ROOT = Path(__file__).resolve().parent.parent
HEADER = ROOT / "simulator" / "include" / "value_table.h"


def load(paths):
    rows = []                # (sequence id, pieces left, i, hold, value)
    skipped = 0
    for sid, path in enumerate(paths):
        with open(path) as f:
            d = json.load(f)
        queue = d.get("queue") or d.get("sequence")
        if d.get("timedOut"):
            skipped += 1     # a timed-out query can hide a transition: values are only lower bounds
            continue
        for i, h, value in d["values"]:
            if h:            # states with an empty hold are too rare to fit
                rows.append((sid, len(queue) - i, i, h, value))
    return rows, skipped


def fit(rows, min_left=30, sweeps=100):
    rows = [r for r in rows if r[1] >= min_left]
    if not rows:
        sys.exit("no usable states: need DP dumps with at least 30 pieces left")
    cells, groups = defaultdict(list), defaultdict(list)
    for k, (sid, left, i, h, value) in enumerate(rows):
        cells[(sid, i)].append(k)
        groups[(h, (i - 1) % 7)].append(k)
    group_of = [(r[3], (r[2] - 1) % 7) for r in rows]
    cell_of = [(r[0], r[2]) for r in rows]
    delta = {g: 0.0 for g in groups}
    level = {}
    for _ in range(sweeps):                       # alternating least squares
        for c, ks in cells.items():
            level[c] = sum(rows[k][4] - delta[group_of[k]] for k in ks) / len(ks)
        for g, ks in groups.items():
            delta[g] = sum(rows[k][4] - level[cell_of[k]] for k in ks) / len(ks)
        for b in range(7):                        # delta averages zero over held pieces
            gs = [g for g in delta if g[1] == b]
            shift = sum(delta[g] for g in gs) / len(gs) if gs else 0.0
            for g in gs:
                delta[g] -= shift
    for c, ks in cells.items():
        level[c] = sum(rows[k][4] - delta[group_of[k]] for k in ks) / len(ks)

    # level = alpha * (pieces left) + gamma(b): one slope, one intercept per bag offset
    left_of = {cell_of[k]: rows[k][1] for k in range(len(rows))}
    by_b = defaultdict(list)
    for (sid, i), v in level.items():
        by_b[(i - 1) % 7].append((left_of[(sid, i)], v))
    sxx = sxy = 0.0
    means = {}
    for b, pts in by_b.items():
        mx = sum(x for x, _ in pts) / len(pts)
        my = sum(y for _, y in pts) / len(pts)
        means[b] = (mx, my)
        sxx += sum((x - mx) ** 2 for x, _ in pts)
        sxy += sum((x - mx) * (y - my) for x, y in pts)
    alpha = sxy / sxx
    gamma = {b: my - alpha * mx for b, (mx, my) in means.items()}
    mean_gamma = sum(gamma.values()) / len(gamma)
    theta = {(h, b): gamma.get(b, mean_gamma) + delta.get((h, b), 0.0) for h in PIECES for b in range(7)}
    spread = max(max(delta.get((h, b), 0.0) for h in PIECES) - min(delta.get((h, b), 0.0) for h in PIECES)
                 for b in range(7))
    info = {"states": len(rows), "sequences": len({r[0] for r in rows}), "spread": spread,
            "missing": sorted(h + str(b) for h in PIECES for b in range(7) if (h, b) not in delta)}
    return alpha, theta, info


def header(alpha, theta, info):
    rows = "\n".join("    {" + ", ".join(f"{theta[(h, b)]:+.4f}" for b in range(7)) + "},  // " + h for h in PIECES)
    return f"""// value_table.h — the fitted value table used by the value-guided online
// algorithm (online.h). GENERATED by tools/fit_value.py; do not edit by hand.
//
//     V(i, h) = VALUE_ALPHA * (pieces left) + VALUE_THETA[h][b],   b = (i - 1) mod 7
//
// Fitted to the exact offline values of {info['states']} boundary states from
// {info['sequences']} seeded 200-piece sequences. Within a bag offset, theta differs by at
// most {info['spread']:.2f} PCs between held pieces: with full knowledge of the future, the
// held piece hardly matters.
#pragma once

namespace tetris {{
namespace online {{

constexpr double VALUE_ALPHA = {alpha:.5f};  // PCs per piece

// Rows: held piece I, O, T, L, J, S, Z. Columns: bag offset 0..6.
constexpr double VALUE_THETA[7][7] = {{
{rows}
}};

}}  // namespace online
}}  // namespace tetris
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("dumps", nargs="+", help="DP_DUMP files, one per sequence")
    ap.add_argument("--out", default=str(HEADER), help="header to write (default: simulator/include/value_table.h)")
    args = ap.parse_args()
    rows, skipped = load(args.dumps)
    alpha, theta, info = fit(rows)
    Path(args.out).write_text(header(alpha, theta, info))
    print(f"fitted {info['states']} states from {info['sequences']} sequences"
          + (f" ({skipped} dumps with timed-out queries skipped)" if skipped else ""))
    print(f"alpha = {alpha:.4f} PCs per piece; held pieces differ by at most {info['spread']:.2f} PCs at one bag offset")
    if info["missing"]:
        print("no data for (hold, bag offset):", " ".join(info["missing"]), "- these use the bag-offset average")
    print("hold   " + "".join(f"  b={b}  " for b in range(7)))
    for h in PIECES:
        print(f"  {h}   " + "".join(f"{theta[(h, b)]:+7.2f}" for b in range(7)))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
